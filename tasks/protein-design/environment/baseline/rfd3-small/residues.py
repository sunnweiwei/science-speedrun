"""Atom14 residue constants.

Each residue is represented by up to 14 heavy atoms in a residue-type-specific order,
the representation RFdiffusion3 uses. Slots 0-3 are always the backbone N, CA, C, O,
so backbone-only logic stays valid on an all-atom array. Tryptophan fills all 14.
"""

ATOM14 = {
    "ALA": ["N", "CA", "C", "O", "CB"],
    "ARG": ["N", "CA", "C", "O", "CB", "CG", "CD", "NE", "CZ", "NH1", "NH2"],
    "ASN": ["N", "CA", "C", "O", "CB", "CG", "OD1", "ND2"],
    "ASP": ["N", "CA", "C", "O", "CB", "CG", "OD1", "OD2"],
    "CYS": ["N", "CA", "C", "O", "CB", "SG"],
    "GLN": ["N", "CA", "C", "O", "CB", "CG", "CD", "OE1", "NE2"],
    "GLU": ["N", "CA", "C", "O", "CB", "CG", "CD", "OE1", "OE2"],
    "GLY": ["N", "CA", "C", "O"],
    "HIS": ["N", "CA", "C", "O", "CB", "CG", "ND1", "CD2", "CE1", "NE2"],
    "ILE": ["N", "CA", "C", "O", "CB", "CG1", "CG2", "CD1"],
    "LEU": ["N", "CA", "C", "O", "CB", "CG", "CD1", "CD2"],
    "LYS": ["N", "CA", "C", "O", "CB", "CG", "CD", "CE", "NZ"],
    "MET": ["N", "CA", "C", "O", "CB", "CG", "SD", "CE"],
    "PHE": ["N", "CA", "C", "O", "CB", "CG", "CD1", "CD2", "CE1", "CE2", "CZ"],
    "PRO": ["N", "CA", "C", "O", "CB", "CG", "CD"],
    "SER": ["N", "CA", "C", "O", "CB", "OG"],
    "THR": ["N", "CA", "C", "O", "CB", "OG1", "CG2"],
    "TRP": ["N", "CA", "C", "O", "CB", "CG", "CD1", "CD2", "NE1", "CE2", "CE3",
            "CZ2", "CZ3", "CH2"],
    "TYR": ["N", "CA", "C", "O", "CB", "CG", "CD1", "CD2", "CE1", "CE2", "CZ", "OH"],
    "VAL": ["N", "CA", "C", "O", "CB", "CG1", "CG2"],
}

# OXT, the C-terminal carboxyl oxygen, is deliberately absent: it occurs once per
# chain and AlphaFold's atom14 layout omits it too. Parsers skip it rather than fail.
IGNORED_ATOMS = {"OXT"}

ATOM14_WIDTH = 14
BACKBONE_SLOTS = (0, 1, 2, 3)
BACKBONE_ATOMS = ("N", "CA", "C", "O")

RESTYPES = tuple(sorted(ATOM14))
RESTYPE_INDEX = {name: index for index, name in enumerate(RESTYPES)}

THREE_TO_ONE = {
    "ALA": "A", "ARG": "R", "ASN": "N", "ASP": "D", "CYS": "C", "GLN": "Q",
    "GLU": "E", "GLY": "G", "HIS": "H", "ILE": "I", "LEU": "L", "LYS": "K",
    "MET": "M", "PHE": "F", "PRO": "P", "SER": "S", "THR": "T", "TRP": "W",
    "TYR": "Y", "VAL": "V",
}

# Alternative naming for symmetric sidechain tips: these pairs are indistinguishable
# by the physics, so a motif RMSD must take the better of the two assignments.
SYMMETRIC_SWAPS = {
    "ARG": [("NH1", "NH2")],
    "ASP": [("OD1", "OD2")],
    "GLU": [("OE1", "OE2")],
    "PHE": [("CD1", "CD2"), ("CE1", "CE2")],
    "TYR": [("CD1", "CD2"), ("CE1", "CE2")],
}


def atom_slot(residue_name, atom_name):
    """Index of `atom_name` within the residue's atom14 layout, or None."""
    names = ATOM14.get(residue_name)
    if names is None or atom_name not in names:
        return None
    return names.index(atom_name)
